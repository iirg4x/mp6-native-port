async page => {
 const fs = require('node:fs/promises');
 const root = 'res/menu/storybook';
 await fs.mkdir(root, {recursive:true});
 // proof.nativeExport() prints the pages with paper ornaments only (no menu).
 await page.goto(new URL(page.url()).origin+'/?still');
 await page.waitForFunction(()=>window.proof?.nativeExport);
 const data=await page.evaluate(()=>window.proof.nativeExport());
 for(const [id,value] of Object.entries(data.images))await fs.writeFile(root+'/'+id+'.png',Buffer.from(value.split(',')[1],'base64'));
 for(const [id,a] of Object.entries(data.assets))await fs.copyFile('docs/design/storybook-generated/'+a.file,root+'/'+id+'.png');
 for(const file of ['TitanOne-Regular.ttf','TitanOne-OFL.txt'])await fs.copyFile('docs/design/storybook-generated/assets/'+file,'res/fonts/'+file);
 let header='// Generated by export-native.cjs from the approved prototype. Do not hand-edit.\n#pragma once\nnamespace mp6::ui::storybook_art {\nstruct Sprite { const char* name; float width,height,x,y,w,h; };\ninline constexpr Sprite sprites[] = {\n';
 for(const [id,a] of Object.entries(data.assets))header+=' {"'+id+'",'+[...a.size,...a.content].join(',')+'},\n';
 for(const id of ['book-left','book-right','paper-left','paper-right'])header+=' {"'+id+'",'+[data.leafSize,data.leafSize,0,0,data.leafSize,779*data.leafResolution].join(',')+'},\n';
 for(const [id,h] of [['cloud',82],['cloud-bank',83],['cloud-round',118]])header+=' {"'+id+'",264,'+(h+12)+',0,0,264,'+(h+12)+'},\n';
 header+='};\nstruct Band { float top,bottom; };\ninline constexpr Band profile[] = {\n';
 header+=data.profile.map(p=>' {'+p.top.toFixed(6)+'f,'+p.bottom.toFixed(6)+'f}').join(',\n');
 header+='\n};\n}\n';
 await fs.writeFile('src/gx/ui/storybook_art_data.hpp',header);
 return {sprites:Object.keys(data.assets).length+Object.keys(data.images).length,leafSize:data.leafSize,destination:root};
}
