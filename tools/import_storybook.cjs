// Mechanical asset build: reuses the preview's own export, not a screenshot.
// Run after capture-native.cjs through Playwright CLI.
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
 const root=path.resolve(__dirname,'..');process.chdir(root);
 const data=JSON.parse(await fs.readFile(process.argv[2]||'output/playwright/storybook-native.json','utf8'));
 const out='res/menu/storybook';await fs.mkdir(out,{recursive:true});
 for(const [id,value] of Object.entries(data.images))if(id!=='day-mask')await fs.writeFile(out+'/'+id+'.png',Buffer.from(value.split(',')[1],'base64'));
 for(const [id,a] of Object.entries(data.assets))await fs.copyFile('docs/design/storybook-generated/'+a.file,out+'/'+id+'.png');
 for(const file of ['TitanOne-Regular.ttf','TitanOne-OFL.txt'])await fs.copyFile('docs/design/storybook-generated/assets/'+file,'res/fonts/'+file);
 let h='// Generated by tools/import_storybook.cjs from the approved preview export.\n#pragma once\nnamespace mp6::ui::storybook_art {\nstruct Sprite { const char* name; float width,height,x,y,w,h; };\ninline constexpr Sprite sprites[] = {\n';
 const sprite=(id,v)=>h+=' {"'+id+'",'+v.map(n=>Number(n).toFixed(6)+'f').join(',')+'},\n';
 for(const [id,a] of Object.entries(data.assets))sprite(id,[...a.size,...a.content]);
 for(const id of ['book-left','book-right','paper-left','paper-right'])sprite(id,[data.leafSize,data.leafSize,0,0,data.leafSize,data.layout.book.h*data.leafResolution]);
 for(const [id,height] of [['cloud',82],['cloud-bank',83],['cloud-round',118]])sprite(id,[264,height+12,0,0,264,height+12]);
 h+='};\nstruct Band { float top,bottom; };\n';
 for(const key of ['profile','sheet'])h+='inline constexpr Band '+key+'[] = {\n'+data[key].map(p=>' {'+p.top.toFixed(6)+'f,'+p.bottom.toFixed(6)+'f}').join(',\n')+'\n};\n';
 h+='}\n';await fs.writeFile('src/gx/ui/storybook_art_data.hpp',h);
 console.log('Imported '+(Object.keys(data.assets).length+Object.keys(data.images).length)+' independent sprites, paper profiles and Titan One.');
})().catch(error=>{console.error(error);process.exitCode=1;});
